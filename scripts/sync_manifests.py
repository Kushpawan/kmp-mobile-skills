#!/usr/bin/env python3
"""Keep every agent manifest and the README catalog in sync with skills/.

What it writes:
  * the `skills` list in .codex-plugin/plugin.json and .cursor-plugin/plugin.json
  * the `version` field in every manifest (only when --version is given)
  * the skill catalog in README.md between the catalog markers

Usage:
    python3 scripts/sync_manifests.py                 # rewrite files in place
    python3 scripts/sync_manifests.py --check         # exit 1 if anything is out of date (CI)
    python3 scripts/sync_manifests.py --version 0.2.0 # also set the release version everywhere
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from skilllib import REPO_ROOT, SKILLS_DIR, FrontmatterError, read_document, skill_dirs  # noqa: E402

VERSIONED_MANIFESTS = [
    "plugin.json",
    ".claude-plugin/plugin.json",
    ".codex-plugin/plugin.json",
    ".cursor-plugin/plugin.json",
    "gemini-extension.json",
]
SKILL_LISTS = {
    ".codex-plugin/plugin.json": "./skills/{name}",
    ".cursor-plugin/plugin.json": "skills/{name}",
}
README = "README.md"
CATALOG_START = "<!-- catalog:start -->"
CATALOG_END = "<!-- catalog:end -->"
CATEGORY_TITLES = [
    ("build", "Build: project and modules"),
    ("ui", "UI"),
    ("data", "Data"),
    ("ios-interop", "iOS interop"),
    ("testing", "Testing"),
    ("debug", "Debug and fix"),
    ("performance", "Performance"),
    ("review", "Review"),
    ("workflow", "Plan and implement"),
    ("release", "Release and CI"),
    ("migration", "Migration"),
    ("tooling", "Tooling"),
]
SEMVER_RE = re.compile(r"^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$")


def load_skills() -> list[dict]:
    skills = []
    for skill_dir in skill_dirs(SKILLS_DIR):
        skill_md = skill_dir / "SKILL.md"
        if not skill_md.is_file():
            continue
        try:
            fm = read_document(skill_md).frontmatter
        except FrontmatterError:
            continue
        metadata = fm.get("metadata") if isinstance(fm.get("metadata"), dict) else {}
        skills.append({
            "name": skill_dir.name,
            "description": str(fm.get("description", "")),
            "category": metadata.get("category", "tooling"),
            "platforms": metadata.get("platforms", ""),
        })
    return skills


def summarize(description: str, limit: int = 170) -> str:
    text = re.sub(r"^Use when\s+", "", description.strip())
    text = re.sub(r"\s+", " ", text)
    if len(text) > limit:
        text = text[:limit].rsplit(" ", 1)[0].rstrip(",;:—-") + "…"
    return text.replace("|", "\\|")


def render_catalog(skills: list[dict]) -> str:
    lines = [CATALOG_START, ""]
    by_category: dict[str, list[dict]] = {}
    for skill in skills:
        by_category.setdefault(skill["category"], []).append(skill)
    known = [key for key, _ in CATEGORY_TITLES]
    for key, title in CATEGORY_TITLES + [(k, k) for k in sorted(by_category) if k not in known]:
        group = by_category.get(key)
        if not group:
            continue
        lines += [f"### {title}", "", "| Skill | Platforms | Use it when |", "|---|---|---|"]
        for skill in sorted(group, key=lambda s: s["name"]):
            platforms = skill["platforms"].replace(",", " +").replace("  ", " ")
            lines.append(f"| [`{skill['name']}`](skills/{skill['name']}/SKILL.md) | {platforms} | {summarize(skill['description'])} |")
        lines.append("")
    lines.append(f"_{len(skills)} skills. Generated by `scripts/sync_manifests.py`; do not edit by hand._")
    lines += ["", CATALOG_END]
    return "\n".join(lines)


def planned_changes(version: str | None) -> dict[Path, str]:
    skills = load_skills()
    names = [s["name"] for s in skills]
    changes: dict[Path, str] = {}

    for rel in VERSIONED_MANIFESTS:
        path = REPO_ROOT / rel
        if not path.is_file():
            continue
        original = path.read_text(encoding="utf-8")
        data = json.loads(original)
        if version:
            data["version"] = version
        if rel in SKILL_LISTS:
            data["skills"] = [SKILL_LISTS[rel].format(name=n) for n in names]
        updated = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
        if updated != original:
            changes[path] = updated

    readme = REPO_ROOT / README
    if readme.is_file():
        original = readme.read_text(encoding="utf-8")
        pattern = re.compile(re.escape(CATALOG_START) + r".*?" + re.escape(CATALOG_END), re.DOTALL)
        if pattern.search(original):
            updated = pattern.sub(lambda _: render_catalog(skills), original)
            if updated != original:
                changes[readme] = updated
    return changes


def manifest_versions() -> dict[str, str]:
    versions = {}
    for rel in VERSIONED_MANIFESTS:
        path = REPO_ROOT / rel
        if path.is_file():
            versions[rel] = json.loads(path.read_text(encoding="utf-8")).get("version", "")
    return versions


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="do not write; exit 1 if files are out of date")
    parser.add_argument("--version", help="semantic version to write into every manifest, e.g. 0.2.0")
    args = parser.parse_args(argv)

    if args.version and not SEMVER_RE.match(args.version):
        print(f"ERROR: --version {args.version!r} is not semantic versioning (X.Y.Z)")
        return 1

    changes = planned_changes(args.version)
    versions = manifest_versions()
    mismatched = len(set(versions.values())) > 1 and not args.version

    if args.check:
        for path in changes:
            print(f"OUT OF DATE {path.relative_to(REPO_ROOT)}")
        if mismatched:
            print(f"OUT OF DATE manifest versions differ: {versions}")
        if changes or mismatched:
            print("Run: python3 scripts/sync_manifests.py" + (f" --version {args.version}" if args.version else ""))
            return 1
        print(f"manifests in sync (version {next(iter(versions.values()), '?')}) -> PASS")
        return 0

    for path, content in changes.items():
        path.write_text(content, encoding="utf-8")
        print(f"updated {path.relative_to(REPO_ROOT)}")
    if mismatched:
        print(f"WARNING manifest versions differ: {versions}; pass --version to align them")
        return 1
    if not changes:
        print("nothing to update")
    return 0


if __name__ == "__main__":
    sys.exit(main())
